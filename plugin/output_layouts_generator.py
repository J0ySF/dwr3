import math

max_radius=3
max_radius_squared=max_radius*max_radius

layouts=[]

for rs in range(0,max_radius_squared+1):
    layout=[]
    for z in range(-max_radius,max_radius+1):
        for y in range(-max_radius,max_radius+1):
            for x in range(-max_radius,max_radius+1):
                if x*x + y*y + z*z == rs:
                    layout.append((x, y, z)) 
    if len(layout) > 0:
        duplicate=False
        for (rsl,l) in layouts:
            if (rsl == 0 or (not(duplicate) and rs%rsl==0 and len(l) == len(layout))):
                if rsl == 0:
                    mul=1
                else:
                    mul=math.sqrt(rs//rsl)
                l_scaled=[(x*mul, y*mul, z*mul) for (x, y, z) in l.copy()]
                duplicate=set(layout)==set(l_scaled)
        if not(duplicate):
            layouts.append((rs, layout))

def sec_elem(s):
    return s[1]

layouts=sorted(layouts, key=lambda tup: (len(tup[1]), tup[0]))

