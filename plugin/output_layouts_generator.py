    f.write('typedef enum {\n')
    for (rsl,l) in layouts:
        f.write('\tOUTPUT_LAYOUT_N' + str(len(l)) + '_RS' + str(rsl) + ', \n')
    f.write('\tOUTPUT_LAYOUT_COUNT\n')
    f.write('} OUTPUT_LAYOUT_T;\n')
    f.write('\n')
    f.write('\n')
    f.write('const char *output_layout_name(OUTPUT_LAYOUT_T layout);\n')
    f.write('const int *output_layout_offsets(OUTPUT_LAYOUT_T layout, int* count, int* radius_sq);\n')
    f.write('\n')
    f.write('#ifdef __cplusplus\n')
    f.write('}\n')
